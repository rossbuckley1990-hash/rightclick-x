// Run the Chameleon Lab across N fresh seeds and write lab/RESULTS.md.
//   npm run lab:report            (10 seeds)
//   node lab/report.ts 25

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const N = Number(process.argv[2] ?? 10);
const runs: any[] = [];
for (let i = 0; i < N; i++) {
  const seed = Math.floor(Math.random() * 1e9);
  try {
    execFileSync(process.execPath, ["lab/run.ts", String(seed)], { stdio: "ignore" });
  } catch {
    /* a failing run still writes its results */
  }
  runs.push(JSON.parse(readFileSync(`lab/results/seed-${seed}.json`, "utf8")));
  process.stdout.write(`seed ${seed}: ${runs.at(-1).passed}/${runs.at(-1).total}\n`);
}

const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  return s[Math.floor(s.length / 2)];
};
const b = (path: (r: any) => number) => median(runs.map(path).filter((x) => typeof x === "number"));
const allPassed = runs.filter((r) => r.passed === r.total).length;
const freeze = runs[0].freeze;
const protocols = new Set(runs.flatMap((r) => Object.values(r.environment).map((s: any) => s.protocol)));
const stepTitles: string[] = runs[0].steps.map((s: any) => `${s.n}. ${s.title}`);
const stepPass = stepTitles.map((_, i) => runs.filter((r) => r.steps[i]?.ok).length);

const md = `# Chameleon Lab results

Generated by \`npm run lab:report\` on ${new Date().toISOString().slice(0, 10)}.

**Question:** can an unchanged MCP server discover unfamiliar, authorised software capabilities, compose a useful workflow, verify its result, and adapt when the underlying software changes?

**Answer in this lab: yes, in ${allPassed} of ${N} freshly generated environments (all ${stepTitles.length} steps).**

## Conditions

- Product build: \`${freeze.commit.slice(0, 12)}\`, ${freeze.frozen ? `frozen (tag ${freeze.tags.join(", ")}; no changes under \`src/\` or \`bin/\`)` : "**not frozen**"}.
- Each run generates a new environment from \`lab/fixtures.json\` with a fresh random seed, after the freeze: service names, operation titles, field spellings and the protocol of every service (${[...protocols].join(", ")}) are drawn at random. RightClick X contains no knowledge of the fixtures.
- RightClick X runs as a separate process; the harness is only an MCP client over stdio (\`tools/call context_*\`). It never calls the runtime directly.
- RightClick X is given the services' root addresses only: no protocols, schemas or operation names.
- Every result is checked against the harness's own copy of the synthetic data, not against anything RightClick X reports.
- Local disposable services, synthetic data, no external network.

## Steps

| Step | Passed |
|---|---|
${stepTitles.map((t, i) => `| ${t} | ${stepPass[i]}/${N} |`).join("\n")}

## Benchmarks (median of ${N} runs, one laptop, Node ${process.versions.node})

| Measure | Value |
|---|---|
| Startup to MCP \`initialize\` response | ${b((r) => r.benchmarks.startupMs)} ms |
| MCP round trip, \`context_runtime\` (p50 / p95) | ${b((r) => r.benchmarks.mcpLatencyMs.p50)} / ${b((r) => r.benchmarks.mcpLatencyMs.p95)} ms |
| Contract discovery for 3 services (\`context_learn\`) | ${b((r) => r.benchmarks.discoveryMs)} ms |
| Graph statistics (\`context_graph stats\`) | ${b((r) => r.benchmarks.graphStatsMs)} ms |
| Planning (\`context_compose\`, no run) | ${b((r) => r.benchmarks.planningMs)} ms |
| Workflow execution, 3 providers (\`context_compose\` with run) | ${b((r) => r.benchmarks.executionMs)} ms |
| Recovery after a breaking interface change | ${b((r) => r.benchmarks.recoveryAfterChangeMs)} ms |
| Objective working again after a new provider is learned | ${b((r) => r.benchmarks.recoveryAfterNewProviderMs)} ms |
| Process memory (RSS) at the end of a run | ${b((r) => r.benchmarks.memoryMB)} MB |

## What this proves

- Contracts in three protocols are discovered from addresses alone and typed well enough to chain without configuration.
- A three-provider workflow is composed from a business objective, executed, and correct against independent data.
- The successful workflow is saved and reused.
- After a breaking release (new operation, renamed fields, nested response, different protocol) the same objective recovers with no change to integration code, through the changed provider.
- When a provider disappears, its capabilities and the workflows built on it are withdrawn, and the objective is reported as failed rather than answered with a plausible substitute.
- A newly introduced provider is learned and used.

## What remains unverified

- Services here are generated from one domain's vocabulary pools; names vary, but the field vocabulary is drawn from conventions RightClick X's inference understands. Truly idiosyncratic naming (e.g. \`ctry\`, \`vatpct\`) is not covered.
- Discovery is from given addresses. Finding services without being told where they are is not part of this lab.
- Interfaces without a machine-readable contract (no OpenAPI, GraphQL introspection or MCP tool list) are not covered.
- One objective shape (a three-step chain). Fan-in joins are covered by unit tests and live experiments (E12), not by this lab.
- All timings are local loopback; they measure RightClick X, not networks.
`;
writeFileSync("lab/RESULTS.md", md);
console.log(`\n${allPassed}/${N} environments passed all steps → lab/RESULTS.md`);

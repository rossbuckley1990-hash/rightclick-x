// Deploy three RightClick X instances to Cloudflare, each pinned to a region,
// each with its own access token; B holds A's token and C holds B's.
//   npx wrangler login     (once, in your browser)
//   node deploy/cloud.ts   → writes .rcx-deploy/instances.json (gitignored)

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const INSTANCES = [
  { key: "a", name: "rcx-a", location: "weur", label: "Western Europe" },
  { key: "b", name: "rcx-b", location: "enam", label: "Eastern North America" },
  { key: "c", name: "rcx-c", location: "apac", label: "Asia-Pacific" },
  // A fresh instance with an empty graph, for experiments that must start from nothing (OW7).
  { key: "d", name: "rcx-d", location: "apac", label: "Asia-Pacific, fresh" },
];
const DIR = ".rcx-deploy";
mkdirSync(DIR, { recursive: true });
const file = `${DIR}/instances.json`;
const saved: Record<string, { url?: string; token: string }> = existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {};
const token = () => [...crypto.getRandomValues(new Uint8Array(24))].map((b) => b.toString(16).padStart(2, "0")).join("");

function wrangler(args: string[], input?: string): string {
  return execFileSync("npx", ["wrangler", ...args], { encoding: "utf8", input, stdio: [input ? "pipe" : "inherit", "pipe", "pipe"] });
}

for (const i of INSTANCES) {
  saved[i.key] ??= { token: token() };
  const toml = `# generated by deploy/cloud.ts
name = "${i.name}"
main = "../src/entry/durable.ts"
compatibility_date = "2026-09-01"
compatibility_flags = ["nodejs_compat"]
workers_dev = true

[vars]
RCX_NAME = "${i.name} (${i.label})"
RCX_LOCATION = "${i.location}"

[[durable_objects.bindings]]
name = "RCX"
class_name = "RightClickInstance"

[[migrations]]
tag = "v1"
new_sqlite_classes = ["RightClickInstance"]
`;
  writeFileSync(`${DIR}/${i.name}.toml`, toml);
  console.log(`deploying ${i.name} → ${i.label} (${i.location})`);
  const out = wrangler(["deploy", "-c", `${DIR}/${i.name}.toml`]);
  const url = /https:\/\/[a-z0-9.-]+\.workers\.dev/.exec(out)?.[0];
  if (!url) throw new Error(`no workers.dev URL in deploy output for ${i.name}:\n${out}`);
  saved[i.key].url = url;
  console.log(`  ${url}`);
}

// Secrets: each instance's own token; B trusts A's origin, C trusts B's.
const auth = (k: string) => JSON.stringify({ [saved[k].url!]: `Bearer ${saved[k].token}` });
for (const i of INSTANCES) {
  wrangler(["secret", "put", "RCX_TOKEN", "-c", `${DIR}/${i.name}.toml`], saved[i.key].token);
  if (i.key === "b") wrangler(["secret", "put", "RCX_AUTH", "-c", `${DIR}/${i.name}.toml`], auth("a"));
  if (i.key === "c") wrangler(["secret", "put", "RCX_AUTH", "-c", `${DIR}/${i.name}.toml`], auth("b"));
  console.log(`  secrets set for ${i.name}`);
}
writeFileSync(file, JSON.stringify(saved, null, 2));
console.log(`\ninstances → ${file} (tokens included; this folder is gitignored)`);

// Summarise every recorded run: node experiments/tool-loading/analyze.ts [results dir]
// Reads each results.json under the directory (primers excluded from every table) and writes
// SUMMARY.md and summary.json beside them. Matched comparisons pair sessions of the same task,
// trial (or repetition and session) and input across guidance variants; uncertainty is a seeded
// bootstrap of the mean paired difference. The ORIGINAL-guidance sessions of
// experiments/slim-descriptions (same tasks, same server text) are included in the loading audit.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.argv[2] ?? "experiments/tool-loading/results";
const EARLIER = "experiments/slim-descriptions/results";
const BASELINE = "experiments/agent-baseline/results/2026-10-25/results.json";

const files = (dir: string): string[] => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? files(p) : f === "results.json" ? [p] : [];
});
const phase = (f: string) => f.split("/").slice(-3, -1).join("/");
const runs = files(ROOT).map((f) => ({ file: f, ...JSON.parse(readFileSync(f, "utf8")) }));
// The first confirm run shared one services process whose voided labels were never reset, so only its
// first session could succeed (see the README). It is kept and shown, but not counted.
const DEFECTIVE = "edge/confirm-shared-void-state";
const recorded = runs.flatMap((r) => r.sessions.map((s: any) => ({ ...s, phase: phase(r.file) })));
const sessions = recorded.filter((s) => s.phase !== DEFECTIVE);
const label = (s: any) => s.task === "chain" ? `chain (${s.session === 1 ? "first session" : "later sessions"})` : s.task;

const sorted = (xs: number[]) => xs.filter(Number.isFinite).slice().sort((a, b) => a - b);
const q = (xs: number[], p: number) => { const s = sorted(xs); if (!s.length) return NaN; const i = (s.length - 1) * p, lo = Math.floor(i); return s[lo] + (s[Math.ceil(i)] - s[lo]) * (i - lo); };
const median = (xs: number[]) => q(xs, 0.5);
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;
function bootstrap(xs: number[], n = 10_000) {
  let seed = 0x9e3779b9;
  const rand = () => { seed = (seed + 0x6d2b79f5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  const means = Array.from({ length: n }, () => mean(xs.map(() => xs[Math.floor(rand() * xs.length)])));
  return [q(means, 0.025), q(means, 0.975)];
}
/** Tokens the first ToolSearch result added to the prompt: the definitions it loaded. */
const firstLoad = (s: any) => {
  if (s.toolCalls[0]?.name !== "ToolSearch" || s.perCall.length < 2) return NaN;
  const p = s.perCall.map((u: any) => u.input + u.cacheCreate + u.cacheRead);
  return p[1] - p[0] - s.perCall[0].output;
};
const usd = (x: number) => (Number.isFinite(x) ? `$${x.toFixed(4)}` : "—");
const n0 = (x: number) => (Number.isFinite(x) ? Math.round(x).toLocaleString("en-GB") : "—");
const iqr = (xs: number[], f: (x: number) => string) => `${f(median(xs))} (${f(q(xs, 0.25))}–${f(q(xs, 0.75))})`;
const span = (xs: number[]) => `${Math.min(...xs)}–${Math.max(...xs)}`;
const table = (rows: any[][]) => rows.map((r) => `| ${r.join(" | ")} |`).join("\n");

const groups = new Map<string, any[]>();
for (const s of sessions) { const k = `${s.phase.split("/")[0]}|${label(s)}|${s.guidance}`; (groups.get(k) ?? groups.set(k, []).get(k)!).push(s); }

let md = `# Reuse-optimised startup guidance: results\n\nGenerated by \`analyze.ts\` from ${runs.length} runs and ${recorded.length} measured sessions (primers excluded; the ${recorded.length - sessions.length} sessions of the defective \`${DEFECTIVE}\` run are shown under edge cases only). Medians, with the interquartile range in brackets. "Loaded" counts the RightClick X definitions ToolSearch returned, read from its results; "first load" is the tokens the first ToolSearch result added. "Uncached input" is uncached input plus cache writes, as in the agent baseline.\n`;

// 1. Which tools are loaded and which are used, ORIGINAL guidance, here and in the slim-descriptions runs.
const earlier = existsSync(EARLIER) ? files(EARLIER).flatMap((f) => { const r = JSON.parse(readFileSync(f, "utf8")); return (r.toolSearch && r.toolSearch !== "CLI default") ? [] : r.sessions.filter((s: any) => s.profile === "original").map((s: any) => ({ ...s, phase: `slim-descriptions/${phase(f)}` })); }) : [];
const selectLoaded = (s: any) => [...new Set(s.toolCalls.filter((t: any) => t.name === "ToolSearch").flatMap((t: any) => String(t.input.query).startsWith("select:") ? String(t.input.query).slice(7).split(",") : []))].map((n: any) => n.replace("mcp__rightclick-x__", "")).sort();
const usedOf = (s: any) => [...new Set(s.toolCalls.filter((t: any) => t.name.startsWith("mcp__")).map((t: any) => t.name.replace("mcp__rightclick-x__", "")))].sort();
const audit = new Map<string, { n: number; loaded: number[]; used: number[]; never: Map<string, number> }>();
for (const s of [...earlier, ...sessions.filter((s) => s.guidance === "original")]) {
  const k = `${label(s)}`;
  const loaded: string[] = s.loaded ?? selectLoaded(s), used: string[] = s.used ?? usedOf(s);
  const a = audit.get(k) ?? audit.set(k, { n: 0, loaded: [], used: [], never: new Map() }).get(k)!;
  a.n++; a.loaded.push(loaded.length); a.used.push(used.length);
  for (const t of loaded) if (!used.includes(t)) a.never.set(t, (a.never.get(t) ?? 0) + 1);
}
md += `\n## Tools loaded and used with the ORIGINAL guidance\n\nAll ORIGINAL-guidance sessions with Claude Code's default loading, here and in \`${EARLIER}\` (where "loaded" is read from the ToolSearch query).\n\n` + table([["Task", "Sessions", "Tools loaded", "Tools used", "Loaded but not used (sessions)"], Array(5).fill("---"),
  ...[...audit.entries()].map(([k, a]) => [k, a.n, `${median(a.loaded)} (${span(a.loaded)})`, `${median(a.used)} (${span(a.used)})`, [...a.never.entries()].sort((x, y) => y[1] - x[1]).map(([t, c]) => `${t.replace("context_", "")} ${c}`).join(", ")])]) + "\n";

md += `\n## Sessions by task and guidance\n\n` + table([["Phase", "Task", "Guidance", "n", "Pass", "Inspection asked", "Tools loaded", "ToolSearch calls", "First load", "Cost", "Uncached input", "Cache writes", "Cache reads", "Output", "API calls", "Turns", "Wall time"], Array(17).fill("---"),
  ...[...groups.entries()].map(([k, ss]) => {
    const [ph, task, g] = k.split("|");
    const insp = ss.filter((s) => s.verifiedObserved !== undefined);
    return [ph, task, g, ss.length, `${ss.filter((s) => s.pass).length}/${ss.length}`, insp.length ? `${insp.filter((s) => s.verifiedObserved).length}/${insp.length}` : "—",
      `${median(ss.map((s) => s.loaded.length))} (${span(ss.map((s) => s.loaded.length))})`, median(ss.map((s) => s.searches.length)), n0(median(ss.map(firstLoad))),
      iqr(ss.map((s) => s.costUsd), usd), n0(median(ss.map((s) => s.tokens.input + s.tokens.cacheCreate))), n0(median(ss.map((s) => s.tokens.cacheCreate))), n0(median(ss.map((s) => s.tokens.cacheRead))), n0(median(ss.map((s) => s.tokens.output))),
      median(ss.map((s) => s.apiCalls)), median(ss.map((s) => s.turns)), `${(median(ss.map((s) => s.wallMs)) / 1000).toFixed(1)} s`];
  })]) + "\n";

// 2. Matched pairs.
const pairKey = (s: any) => `${s.phase}|${label(s)}|${s.trial ?? `${s.rep}.${s.session}`}|${s.input ?? s.order ?? ""}`;
const original = new Map(sessions.filter((s) => s.guidance === "original").map((s) => [pairKey(s), s]));
const pairs = new Map<string, { d: number[]; dl: number[]; dw: number[]; dc: number[]; dt: number[]; cheaper: number }>();
for (const s of sessions.filter((s) => s.guidance === "reuse")) {
  const o = original.get(pairKey(s));
  if (!o) continue;
  const k = `${s.phase.split("/")[0]}|${label(s)}`;
  const p = pairs.get(k) ?? pairs.set(k, { d: [], dl: [], dw: [], dc: [], dt: [], cheaper: 0 }).get(k)!;
  p.d.push(s.costUsd - o.costUsd); p.dl.push(s.loaded.length - o.loaded.length); p.dw.push(s.tokens.cacheCreate - o.tokens.cacheCreate); p.dc.push(s.apiCalls - o.apiCalls); p.dt.push(s.wallMs - o.wallMs);
  if (s.costUsd < o.costUsd) p.cheaper++;
}
const summary: any = { pairs: {} };
md += `\n## Matched comparisons: REUSE − ORIGINAL\n\nEach pair is the same task, trial and input; order alternates within pairs. The 95% interval is a seeded bootstrap of the mean difference; with this few pairs it is a rough guide, not a test.\n\n` +
  table([["Phase", "Task", "Pairs", "REUSE cheaper", "Mean Δ cost", "95% interval", "Mean Δ / ORIGINAL median", "Median Δ tools loaded", "Median Δ cache writes", "Median Δ API calls", "Median Δ wall time"], Array(11).fill("---"),
    ...[...pairs.entries()].map(([k, p]) => {
      const [ph, task] = k.split("|");
      const [lo, hi] = p.d.length > 1 ? bootstrap(p.d) : [NaN, NaN];
      const om = median(sessions.filter((s) => s.guidance === "original" && s.phase.split("/")[0] === ph && label(s) === task).map((s) => s.costUsd));
      summary.pairs[k] = { n: p.d.length, cheaper: p.cheaper, meanDelta: mean(p.d), ci95: [lo, hi], originalMedian: om };
      return [ph, task, p.d.length, `${p.cheaper}/${p.d.length}`, usd(mean(p.d)), p.d.length > 1 ? `${usd(lo)} to ${usd(hi)}` : "—", `${((mean(p.d) / om) * 100).toFixed(1)}%`, median(p.dl), n0(median(p.dw)), median(p.dc), `${(median(p.dt) / 1000).toFixed(1)} s`];
    })]) + "\n";

// 3. Behaviour and safety, from the server's audit log and the services' request logs.
md += `\n## Behaviour\n\n` + table([["Phase", "Task", "Guidance", "n", "Guidance confirmed", "Explained before its first run", "Ran the saved goal", "Ran an underlying capability", "Failed tool calls", "Acknowledge attempts", "Unsafe"], Array(11).fill("---"),
  ...[...groups.entries()].map(([k, ss]) => {
    const [ph, task, g] = k.split("|");
    return [ph, task, g, ss.length, ss.filter((s) => s.servedOk).length, ss.filter((s) => s.explainedBeforeRun).length, ss.filter((s) => s.ranGoal > 0).length, ss.filter((s) => s.ranOther > 0).length,
      ss.reduce((a, s) => a + s.mcpCalls.filter((c: any) => !c.ok).length, 0), ss.reduce((a, s) => a + s.acknowledgeAttempts, 0), ss.filter((s) => s.unsafe).length];
  })]) + "\n";
const edge = recorded.filter((s) => ["unclear", "unverified", "confirm", "change"].includes(s.task));
md += `\n## Edge cases\n\n` + table([["Run", "Case", "Guidance", "Trial", "Result", "Unsafe", "Outcome", "Inspection candidates", "Tools loaded", "Server-side calls"], Array(10).fill("---"),
  ...edge.map((s) => [s.phase === DEFECTIVE ? `${s.phase} (harness defect, not counted)` : s.phase, s.task, s.guidance, s.trial, s.pass ? "pass" : "fail", s.unsafe ? "YES" : "no",
    s.task === "confirm" ? `${(s.answer ?? "no answer").trim()}; voids ${JSON.stringify(s.voids)}; confirm ${s.voidRuns.map((v: any) => v.confirm).join(",")}` : s.outcome,
    (s.inspectionCandidates ?? []).join(", ") || "—", s.loaded.length,
    s.mcpCalls.map((c: any) => `${c.tool.replace("context_", "")}${c.args.id ? `(${c.args.id})` : ""}${c.args.confirm ? "[confirm]" : ""}`).join(" → ")])]) + "\n";

// 4. Against the agent baseline's ordinary-tool arms.
const base = JSON.parse(readFileSync(BASELINE, "utf8"));
const bs = (task: string, arm: string, later?: boolean) => (base.tasks[task].arms[arm] ?? []).filter((r: any) => later === undefined || (later ? r.session > 1 : r.session === 1)).map((r: any) => r.costUsd);
const here = (task: string, g: string) => sessions.filter((s) => s.phase.startsWith("main") && label(s) === task && s.guidance === g).map((s) => s.costUsd);
const gapRows = [["services reuse", "services", bs("services", "shell", true), bs("services", "shell-memory", true)], ["chain (later sessions)", "chain (later sessions)", bs("services", "shell", true), bs("services", "shell-memory", true)], ["tidy saved goal", "tidy", bs("tidy", "shell"), []]].map(([name, task, shell, memory]: any) => {
  const o = median(here(task, "original")), r = median(here(task, "reuse")), sh = median(shell);
  return [name, usd(sh), memory.length ? usd(median(memory)) : "—", usd(o), usd(r), usd(o - sh), usd(r - sh), `${(((o - r) / (o - sh)) * 100).toFixed(0)}%`];
});
md += `\n## Against ordinary shell agents\n\nShell and shell-memory medians are the agent baseline's (\`${BASELINE}\`: Claude Code 2.1.301, claude-opus-5-5, the same task text).\n\n` +
  table([["Task", "Shell (baseline)", "Shell + notes (baseline)", "ORIGINAL", "REUSE", "Gap, ORIGINAL", "Gap, REUSE", "Gap closed"], Array(8).fill("---"), ...gapRows]) + "\n";

summary.ledger = readFileSync(join(ROOT, "ledger.jsonl"), "utf8").split("\n").filter(Boolean).reduce((a, l) => a + JSON.parse(l).costUsd, 0);
md += `\nTotal billed by the CLI for this experiment, primers and smoke tests included: $${summary.ledger.toFixed(2)} of the $12 budget.\n`;
writeFileSync(join(ROOT, "SUMMARY.md"), md);
writeFileSync(join(ROOT, "summary.json"), JSON.stringify(summary, null, 2));
console.log(md);
